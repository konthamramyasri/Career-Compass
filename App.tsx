
import React, { useState, useEffect, useRef } from 'react';
import { Navbar } from './components/Navbar';
import { Footer } from './components/Footer';
import { Wizard } from './components/Wizard';
import { Results } from './components/Results';
import { LoadingSpinner } from './components/LoadingSpinner';
import type { FormData, CareerPlan } from './types';
import { generateCareerPlan } from './services/geminiService';

declare global {
  interface Window {
    VANTA: any;
    // FIX: Use a consistent type for feather across declarations to resolve the TypeScript error.
    feather: {
      replace: () => void;
    };
  }
}

type AppState = 'wizard' | 'loading' | 'results';

const App: React.FC = () => {
  const [appState, setAppState] = useState<AppState>('wizard');
  const [careerPlan, setCareerPlan] = useState<CareerPlan | null>(null);
  const [error, setError] = useState<string | null>(null);
  
  const vantaRef = useRef<HTMLDivElement>(null);
  const [vantaEffect, setVantaEffect] = useState<any>(null);

  useEffect(() => {
    if (!vantaEffect && vantaRef.current && window.VANTA) {
      setVantaEffect(window.VANTA.GLOBE({
        el: vantaRef.current,
        mouseControls: true,
        touchControls: true,
        gyroControls: false,
        minHeight: 200.00,
        minWidth: 200.00,
        scale: 1.00,
        scaleMobile: 1.00,
        color: 0x5b6ef7,
        backgroundColor: 0xf8fafc
      }));
    }
    return () => {
      if (vantaEffect) vantaEffect.destroy();
    };
  }, [vantaEffect]);


  const handleWizardSubmit = async (formData: FormData) => {
    setAppState('loading');
    setError(null);
    try {
      const plan = await generateCareerPlan(formData);
      setCareerPlan(plan);
      setAppState('results');
    } catch (e) {
      console.error(e);
      setError('Sorry, we couldn\'t generate your career plan. Please try again.');
      setAppState('wizard');
    }
  };

  const handleStartOver = () => {
    setCareerPlan(null);
    setAppState('wizard');
  }

  return (
    <div className="min-h-screen flex flex-col">
      <Navbar />
      <main className="flex-grow">
        <div ref={vantaRef} className="absolute top-0 left-0 w-full h-full z-0"></div>
        <div className="relative z-10 max-w-4xl mx-auto px-4 py-8 sm:py-16">
          <div className="bg-white rounded-xl shadow-2xl p-6 sm:p-8 backdrop-blur-sm bg-opacity-90">
            {appState === 'wizard' && <Wizard onSubmit={handleWizardSubmit} error={error} />}
            {appState === 'loading' && (
               <div className="mt-8 text-center py-12">
                  <LoadingSpinner />
                  <h3 className="text-xl font-semibold text-gray-700">Analyzing your career path...</h3>
                  <p className="text-gray-600 mt-2">Your personalized Career Compass is being generated by Gemini.</p>
               </div>
            )}
            {appState === 'results' && careerPlan && <Results plan={careerPlan} onStartOver={handleStartOver} />}
          </div>
        </div>
      </main>
      <Footer />
    </div>
  );
};

export default App;
